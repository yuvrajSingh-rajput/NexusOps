@Service
public class TaskService {

    private static final Logger log = LoggerFactory.getLogger(TaskService.class);

    private final TaskRepository taskRepository;
    private final TaskCommentRepository commentRepository;
    private final TaskHistoryRepository historyRepository;
    private final SequenceGeneratorService sequenceGenerator;
    private final IdentityService identityService;
    private final RequestService requestService;
    private final WorkflowEngineService workflowEngineService;
    private final com.nexusops.shared.events.OutboxService outboxService;

    public TaskService(TaskRepository taskRepository,
                       TaskCommentRepository commentRepository,
                       TaskHistoryRepository historyRepository,
                       SequenceGeneratorService sequenceGenerator,
                       IdentityService identityService,
                       RequestService requestService,
                       WorkflowEngineService workflowEngineService,
                       com.nexusops.shared.events.OutboxService outboxService) {
        this.taskRepository = taskRepository;
        this.commentRepository = commentRepository;
        this.historyRepository = historyRepository;
        this.sequenceGenerator = sequenceGenerator;
        this.identityService = identityService;
        this.requestService = requestService;
        this.workflowEngineService = workflowEngineService;
        this.outboxService = outboxService;
    }

    @EventListener
    public void onTaskRequested(TaskRequestedEvent event) {
        log.info("Handling TaskRequestedEvent for request {} at node {}", event.requestId(), event.nodeInstanceId());

        RequestResponseDto request = null;
        try {
            request = requestService.getRequest(event.organizationId(), event.requestId());
        } catch (Exception ignored) {}

        String taskTitle = event.title() != null && !event.title().isBlank()
                ? event.title()
                : (request != null ? "Fulfill " + request.title() : "Fulfillment Task");

        String description = "Operational fulfillment task generated by workflow node: " + event.taskKey();
        Map<String, Object> payload = request != null ? request.payload() : event.nodeConfiguration();

        int timeoutHours = 72;
        if (event.nodeConfiguration() != null && event.nodeConfiguration().containsKey("timeoutHours")) {
            try {
                timeoutHours = Integer.parseInt(String.valueOf(event.nodeConfiguration().get("timeoutHours")));
            } catch (Exception ignored) {}
        }
        Instant dueAt = Instant.now().plus(Duration.ofHours(timeoutHours));

        createWorkflowTask(
                event.organizationId(),
                taskTitle,
                description,
                event.requestId(),
                event.workflowInstanceId(),
                event.nodeInstanceId(),
                null,
                null,
                TaskPriority.HIGH,
                payload,
                dueAt
        );
    }

    @Transactional
    public TaskEntity createWorkflowTask(UUID organizationId, String title, String description,
                                         UUID requestId, UUID workflowInstanceId, UUID nodeInstanceId,
                                         UUID teamId, UUID assigneeMembershipId, TaskPriority priority,
                                         Map<String, Object> payload, Instant dueAt) {
        String taskNumber = sequenceGenerator.generateNextSequenceNumber(organizationId, "TASK", "TASK");

        TaskEntity task = new TaskEntity(
                organizationId,
                taskNumber,
                title,
                description,
                requestId,
                workflowInstanceId,
                nodeInstanceId,
                teamId,
                assigneeMembershipId,
                priority,
                payload,
                dueAt
        );

        task = taskRepository.save(task);

        // Record history
        TaskHistoryEntity history = new TaskHistoryEntity(
                organizationId,
                task.getId(),
                assigneeMembershipId != null ? assigneeMembershipId : organizationId,
                "CREATED",
                Map.of(),
                Map.of("taskNumber", taskNumber, "status", task.getStatus().name())
        );
        historyRepository.save(history);

        Map<String, Object> eventPayload = new HashMap<>();
        eventPayload.put("taskId", task.getId().toString());
        eventPayload.put("taskNumber", task.getTaskNumber());
        eventPayload.put("title", task.getTitle());
        eventPayload.put("status", task.getStatus().name());
        if (requestId != null) {
            eventPayload.put("requestId", requestId.toString());
        }
        if (assigneeMembershipId != null) {
            eventPayload.put("assigneeMembershipId", assigneeMembershipId.toString());
        }
        outboxService.publish(organizationId, "TASK_CREATED", "TASK", task.getId(), eventPayload);

        log.info("Created task {} ({}) for request {}", task.getTaskNumber(), task.getId(), requestId);
        return task;
    }

    @Transactional
    public TaskResponseDto claimTask(UUID organizationId, UUID taskId, UserPrincipal principal) {
        log.info("User {} claiming task {}", principal.getMembershipId(), taskId);

        TaskEntity task = taskRepository.findByIdAndOrganizationId(taskId, organizationId)
                .orElseThrow(() -> new ResourceNotFoundException("Task not found with id: " + taskId));

        if (task.getStatus() == TaskStatus.COMPLETED || task.getStatus() == TaskStatus.CANCELLED) {
            throw new ConflictException("TASK_CLOSED", "Cannot claim a completed or cancelled task.");
        }

        Map<String, Object> oldState = Map.of(
                "assigneeMembershipId", String.valueOf(task.getAssigneeMembershipId()),
                "status", task.getStatus().name()
        );

        task.setAssigneeMembershipId(principal.getMembershipId());
        task.setStatus(TaskStatus.IN_PROGRESS);
        task = taskRepository.save(task);

        Map<String, Object> newState = Map.of(
                "assigneeMembershipId", principal.getMembershipId().toString(),
                "status", task.getStatus().name()
        );

        TaskHistoryEntity history = new TaskHistoryEntity(
                organizationId, task.getId(), principal.getMembershipId(), "CLAIMED", oldState, newState
        );
        historyRepository.save(history);

        Map<String, Object> eventPayload = new HashMap<>();
        eventPayload.put("taskId", task.getId().toString());
        eventPayload.put("taskNumber", task.getTaskNumber());
        eventPayload.put("title", task.getTitle());
        eventPayload.put("assigneeMembershipId", principal.getMembershipId().toString());
        eventPayload.put("status", task.getStatus().name());
        outboxService.publish(organizationId, "TASK_ASSIGNED", "TASK", task.getId(), eventPayload);

        return toDto(organizationId, task);
    }

    @Transactional
    public TaskResponseDto assignTask(UUID organizationId, UUID taskId, UUID assigneeMembershipId, UserPrincipal principal) {
        log.info("Assigning task {} to membership {}", taskId, assigneeMembershipId);

        TaskEntity task = taskRepository.findByIdAndOrganizationId(taskId, organizationId)
                .orElseThrow(() -> new ResourceNotFoundException("Task not found with id: " + taskId));

        if (task.getStatus() == TaskStatus.COMPLETED || task.getStatus() == TaskStatus.CANCELLED) {
            throw new ConflictException("TASK_CLOSED", "Cannot assign a closed task.");
        }

        Map<String, Object> oldState = Map.of(
                "assigneeMembershipId", String.valueOf(task.getAssigneeMembershipId()),
                "status", task.getStatus().name()
        );

        task.setAssigneeMembershipId(assigneeMembershipId);
        if (task.getStatus() == TaskStatus.OPEN) {
            task.setStatus(TaskStatus.IN_PROGRESS);
        }
        task = taskRepository.save(task);

        Map<String, Object> newState = Map.of(
                "assigneeMembershipId", assigneeMembershipId.toString(),
                "status", task.getStatus().name()
        );

        TaskHistoryEntity history = new TaskHistoryEntity(
                organizationId, task.getId(), principal.getMembershipId(), "ASSIGNED", oldState, newState
        );
        historyRepository.save(history);

        Map<String, Object> eventPayload = new HashMap<>();
        eventPayload.put("taskId", task.getId().toString());
        eventPayload.put("taskNumber", task.getTaskNumber());
        eventPayload.put("title", task.getTitle());
        if (task.getAssigneeMembershipId() != null) {
            eventPayload.put("assigneeMembershipId", task.getAssigneeMembershipId().toString());
        }
        eventPayload.put("status", task.getStatus().name());
        outboxService.publish(organizationId, "TASK_ASSIGNED", "TASK", task.getId(), eventPayload);

        return toDto(organizationId, task);
    }

    @Transactional
    public TaskResponseDto updateTaskStatus(UUID organizationId, UUID taskId, UpdateTaskStatusDto dto, UserPrincipal principal) {
        log.info("Updating task {} status to {}", taskId, dto.status());

        TaskEntity task = taskRepository.findByIdAndOrganizationId(taskId, organizationId)
                .orElseThrow(() -> new ResourceNotFoundException("Task not found with id: " + taskId));

        verifyTaskAccess(task, principal);

        Map<String, Object> oldState = Map.of("status", task.getStatus().name());

        task.setStatus(dto.status());
        task = taskRepository.save(task);

        Map<String, Object> newState = new HashMap<>();
        newState.put("status", dto.status().name());
        if (dto.notes() != null) {
            newState.put("notes", dto.notes());
        }

        TaskHistoryEntity history = new TaskHistoryEntity(
                organizationId, task.getId(), principal.getMembershipId(), "STATUS_CHANGED", oldState, newState
        );
        historyRepository.save(history);

        Map<String, Object> eventPayload = new HashMap<>();
        eventPayload.put("taskId", task.getId().toString());
        eventPayload.put("taskNumber", task.getTaskNumber());
        eventPayload.put("title", task.getTitle());
        if (task.getAssigneeMembershipId() != null) {
            eventPayload.put("assigneeMembershipId", task.getAssigneeMembershipId().toString());
        }
        eventPayload.put("status", task.getStatus().name());
        outboxService.publish(organizationId, "TASK_UPDATED", "TASK", task.getId(), eventPayload);

        return toDto(organizationId, task);
    }

    @Transactional
    public TaskResponseDto completeTask(UUID organizationId, UUID taskId, CompleteTaskDto dto, UserPrincipal principal) {
        log.info("Completing task {} by membership {}", taskId, principal.getMembershipId());

        TaskEntity task = taskRepository.findByIdAndOrganizationId(taskId, organizationId)
                .orElseThrow(() -> new ResourceNotFoundException("Task not found with id: " + taskId));

        verifyTaskAccess(task, principal);

        if (task.getStatus() == TaskStatus.COMPLETED) {
            throw new ConflictException("TASK_ALREADY_COMPLETED", "Task is already completed.");
        }

        Map<String, Object> oldState = Map.of("status", task.getStatus().name());

        task.setStatus(TaskStatus.COMPLETED);
        task.setCompletedAt(Instant.now());
        if (dto.outputData() != null) {
            task.setOutputData(dto.outputData());
        }
        task = taskRepository.save(task);

        Map<String, Object> newState = new HashMap<>();
        newState.put("status", TaskStatus.COMPLETED.name());
        if (dto.outputData() != null) {
            newState.put("outputData", dto.outputData());
        }
        if (dto.notes() != null) {
            newState.put("notes", dto.notes());
        }

        TaskHistoryEntity history = new TaskHistoryEntity(
                organizationId, task.getId(), principal.getMembershipId(), "COMPLETED", oldState, newState
        );
        historyRepository.save(history);

        // Resume workflow engine if bound to a workflow instance
        if (task.getWorkflowInstanceId() != null) {
            Map<String, Object> signalData = new HashMap<>(dto.outputData() != null ? dto.outputData() : Map.of());
            signalData.put("actorMembershipId", principal.getMembershipId().toString());
            signalData.put("actorEmail", principal.getEmail());
            if (dto.notes() != null) {
                signalData.put("notes", dto.notes());
            }

            workflowEngineService.resumeWorkflowWithSignal(organizationId, task.getWorkflowInstanceId(), "COMPLETED", signalData);
        }

        // Mark request completed if bound to a request
        if (task.getRequestId() != null) {
            try {
                requestService.completeRequest(organizationId, task.getRequestId());
            } catch (Exception e) {
                log.warn("Could not mark request {} completed: {}", task.getRequestId(), e.getMessage());
            }
        }

        Map<String, Object> eventPayload = new HashMap<>();
        eventPayload.put("taskId", task.getId().toString());
        eventPayload.put("taskNumber", task.getTaskNumber());
        eventPayload.put("title", task.getTitle());
        eventPayload.put("status", "COMPLETED");
        if (task.getRequestId() != null) {
            eventPayload.put("requestId", task.getRequestId().toString());
        }
        if (task.getAssigneeMembershipId() != null) {
            eventPayload.put("assigneeMembershipId", task.getAssigneeMembershipId().toString());
        }
        outboxService.publish(organizationId, "TASK_COMPLETED", "TASK", task.getId(), eventPayload);

        return toDto(organizationId, task);
    }

    @Transactional
    public TaskCommentResponseDto addComment(UUID organizationId, UUID taskId, AddTaskCommentDto dto, UserPrincipal principal) {
        TaskEntity task = taskRepository.findByIdAndOrganizationId(taskId, organizationId)
                .orElseThrow(() -> new ResourceNotFoundException("Task not found with id: " + taskId));

        TaskCommentEntity comment = new TaskCommentEntity(
                organizationId, task.getId(), principal.getMembershipId(), dto.content()
        );
        comment = commentRepository.save(comment);

        TaskHistoryEntity history = new TaskHistoryEntity(
                organizationId, task.getId(), principal.getMembershipId(), "COMMENT_ADDED",
                Map.of(), Map.of("commentId", comment.getId().toString())
        );
        historyRepository.save(history);

        String authorName = identityService.getMemberName(organizationId, principal.getMembershipId());
        return new TaskCommentResponseDto(comment.getId(), comment.getAuthorMembershipId(), authorName, comment.getContent(), comment.getCreatedAt());
    }

    @Transactional(readOnly = true)
    public List<TaskResponseDto> getMyTasks(UUID organizationId, UserPrincipal principal) {
        return taskRepository.findAllByOrganizationIdAndAssigneeMembershipIdOrderByCreatedAtDesc(organizationId, principal.getMembershipId())
                .stream().map(t -> toDto(organizationId, t)).toList();
    }

    @Transactional(readOnly = true)
    public List<TaskResponseDto> getQueueTasks(UUID organizationId) {
        return taskRepository.findUnassignedQueueTasks(organizationId)
                .stream().map(t -> toDto(organizationId, t)).toList();
    }

    @Transactional(readOnly = true)
    public TaskResponseDto getTaskById(UUID organizationId, UUID taskId) {
        TaskEntity task = taskRepository.findByIdAndOrganizationId(taskId, organizationId)
                .orElseThrow(() -> new ResourceNotFoundException("Task not found with id: " + taskId));
        return toDto(organizationId, task);
    }

    @Transactional(readOnly = true)
    public List<TaskResponseDto> getTasksForRequest(UUID organizationId, UUID requestId) {
        return taskRepository.findAllByOrganizationIdAndRequestIdOrderByCreatedAtDesc(organizationId, requestId)
                .stream().map(t -> toDto(organizationId, t)).toList();
    }

    private void verifyTaskAccess(TaskEntity task, UserPrincipal principal) {
        if (principal.getAuthorities().stream().anyMatch(a -> a.getAuthority().equals("ROLE_ORG_ADMIN") || a.getAuthority().equals("ORG_ADMIN_MANAGE") || a.getAuthority().equals("TASK_OPERATE"))) {
            return;
        }
        if (task.getAssigneeMembershipId() != null && task.getAssigneeMembershipId().equals(principal.getMembershipId())) {
            return;
        }
        throw new AccessDeniedException("You are not authorized to update or complete this task.");
    }

    private TaskResponseDto toDto(UUID organizationId, TaskEntity entity) {
        RequestResponseDto req = null;
        if (entity.getRequestId() != null) {
            try {
                req = requestService.getRequest(organizationId, entity.getRequestId());
            } catch (Exception ignored) {}
        }

        String assigneeName = "Unassigned";
        if (entity.getAssigneeMembershipId() != null) {
            assigneeName = identityService.getMemberName(organizationId, entity.getAssigneeMembershipId());
        }

        List<TaskCommentResponseDto> comments = commentRepository.findAllByOrganizationIdAndTaskIdOrderByCreatedAtAsc(organizationId, entity.getId())
                .stream().map(c -> new TaskCommentResponseDto(
                        c.getId(),
                        c.getAuthorMembershipId(),
                        identityService.getMemberName(organizationId, c.getAuthorMembershipId()),
                        c.getContent(),
                        c.getCreatedAt()
                )).toList();

        List<TaskHistoryResponseDto> history = historyRepository.findAllByOrganizationIdAndTaskIdOrderByCreatedAtAsc(organizationId, entity.getId())
                .stream().map(h -> new TaskHistoryResponseDto(
                        h.getId(),
                        h.getActorMembershipId(),
                        identityService.getMemberName(organizationId, h.getActorMembershipId()),
                        h.getAction(),
                        h.getOldState(),
                        h.getNewState(),
                        h.getCreatedAt()
                )).toList();

        return new TaskResponseDto(
                entity.getId(),
                entity.getOrganizationId(),
                entity.getTaskNumber(),
                entity.getTitle(),
                entity.getDescription(),
                entity.getRequestId(),
                req != null ? req.requestNumber() : "N/A",
                req != null ? req.title() : "Direct Task",
                entity.getWorkflowInstanceId(),
                entity.getNodeInstanceId(),
                entity.getTeamId(),
                entity.getAssigneeMembershipId(),
                assigneeName,
                entity.getStatus(),
                entity.getPriority(),
                entity.getPayload(),
                entity.getOutputData(),
                entity.getDueAt(),
                entity.getCompletedAt(),
                entity.getCreatedAt(),
                entity.getUpdatedAt(),
                comments,
                history
        );
    }
}

